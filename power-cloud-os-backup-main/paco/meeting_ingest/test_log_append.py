class LogWriter(FakeWriter):
    def __init__(self):
        super().__init__()
        self.old = '# Meetings log\n\n<!-- Generated by '+MARKER+' -->\n\n- Existing meeting\n'
        self.files['log'] = {'id':'log','name':'meetings_log.md','parents':['working'],
            'driveId':'drive','version':'2','mimeType':'text/markdown',
            'appProperties':{'generator':MARKER,'role':'log','plan':'previous'},
            'md5Checksum':hashlib.md5(self.old.encode()).hexdigest()}
    def update_log(self,item):
        self.calls.append('append')
        self.files['log'].update(version='3',md5Checksum=hashlib.md5(item['content'].encode()).hexdigest())
        if self.fail == 'append':
            self.fail = None
            raise TimeoutError('response lost after update')


class AppendLogTests(unittest.TestCase):
    def setUp(self):
        self.tmp=tempfile.TemporaryDirectory();self.addCleanup(self.tmp.cleanup)
        self.journal=Path(self.tmp.name)/'journal.db'
        self.w=LogWriter();self.p=plan()
        self.p['log_update']={**self.w.meta('log'),'content':self.w.old+'\n- Next meeting\n'}
        self.sign()
    def sign(self):
        self.p.pop('sha256',None);self.p['sha256']=digest(self.p)
    def run_plan(self):return execute(self.p,self.w,self.journal,self.p['sha256'])
    def test_append_and_completed_retry_keep_file_id(self):
        self.run_plan();self.run_plan()
        self.assertEqual(self.w.calls.count('append'),1)
        self.assertEqual(len([f for f in self.w.files.values() if f.get('name')=='meetings_log.md']),1)
    def test_lost_response_does_not_append_twice(self):
        self.w.fail='append'
        with self.assertRaises(TimeoutError):self.run_plan()
        self.run_plan();self.assertEqual(self.w.calls.count('append'),1)
    def test_edit_after_preview_stops_before_moves(self):
        self.w.files['log']['version']='4'
        with self.assertRaises(ValueError):self.run_plan()
        self.assertEqual(self.w.calls,[])
    def test_edit_after_completed_append_is_not_overwritten(self):
        self.run_plan();count=len(self.w.calls)
        self.w.files['log']['md5Checksum']='manual-change'
        with self.assertRaises(ValueError):self.run_plan()
        self.assertEqual(len(self.w.calls),count)
    def test_duplicate_filename_holds_before_moves(self):
        self.w.files['otherlog']={**self.w.meta('log'),'id':'otherlog'}
        with self.assertRaises(ValueError):self.run_plan()
        self.assertEqual(self.w.calls,[])
    def test_external_identical_append_requires_journal(self):
        self.w.files['log']['md5Checksum']=hashlib.md5(self.p['log_update']['content'].encode()).hexdigest()
        with self.assertRaises(ValueError):self.run_plan()
        self.assertEqual(self.w.calls,[])
    def test_update_uses_conditional_v2_upload(self):
        session=Mock();session.put.return_value.status_code=200
        writer=GoogleWriter(session,self.w.subject,enabled=True)
        writer.move_meta=Mock(return_value={**self.w.meta('log'),'_etag':'token'})
        writer.update_log(self.p['log_update'])
        args,kwargs=session.put.call_args
        self.assertIn('/upload/drive/v2/files/log',args[0])
        self.assertEqual(kwargs['headers']['If-Match'],'token')
        self.assertEqual(kwargs['data'],self.p['log_update']['content'].encode())
    def test_missing_etag_and_conflict_never_retry(self):
        session=Mock();writer=GoogleWriter(session,self.w.subject,enabled=True)
        writer.move_meta=Mock(return_value=self.w.meta('log'))
        with self.assertRaises(ValueError):writer.update_log(self.p['log_update'])
        session.put.assert_not_called()
        writer.move_meta.return_value['_etag']='old';session.put.return_value.status_code=412
        with self.assertRaises(RuntimeError):writer.update_log(self.p['log_update'])
        session.put.assert_called_once()
    def test_prepare_preserves_existing_text_and_holds_manual_logs(self):
        reader=Mock()
        folders=[{**self.w.meta(k),'mimeType':FOLDER} for k in ('source','working')]
        reader.children.side_effect=lambda p:folders if p=='client' else self.w.children(p)
        def get(api,path,params,raw=False):
            if raw:return self.w.old if path=='files/log' else '# Notes'
            f=self.w.meta(path.split('/')[1]);f['capabilities']={'canAddChildren':True,'canMoveItemIntoTeamDrive':True}
            if f['id']=='original':f['mimeType']='application/vnd.google-apps.document'
            return f
        reader.get.side_effect=get
        event={'id':'e','summary':'Call','start':{'date':'2026-09-11'},'organizer':{'email':self.w.subject},
            'artifacts':[{'id':'original','kind':'notes'}],'discovery_complete':True}
        client={'path':'Acme','folder_id':'client'}
        result=prepare(reader,event,client,self.w.subject)
        self.assertTrue(result['log_update']['content'].startswith(self.w.old))
        self.assertIn('Calendar event: e',result['log_update']['content'])
        self.w.files['log']['appProperties']={}
        with self.assertRaisesRegex(ValueError,'manual'):prepare(reader,event,client,self.w.subject)
